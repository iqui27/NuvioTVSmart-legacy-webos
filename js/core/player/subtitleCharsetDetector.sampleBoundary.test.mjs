import assert from "node:assert/strict";
import test from "node:test";

import { decodeSubtitleBytes } from "./subtitleCharsetDetector.js";

const EUC_KR_SAMPLE = [
  0xbe, 0xc8, 0xb3, 0xe7, 0xc7, 0xcf, 0xbc, 0xbc, 0xbf, 0xe4, 0x20, 0xbc, 0xbc, 0xbb, 0xf3, 0x20,
  0xc7, 0xd1, 0xb1, 0xb9, 0xbe, 0xee, 0x20, 0xc0, 0xda, 0xb8, 0xb7, 0x20, 0xc5, 0xd7, 0xbd, 0xba,
  0xc6, 0xae, 0xc0, 0xd4, 0xb4, 0xcf, 0xb4, 0xd9, 0x20
];

const GB18030_SAMPLE = [
  0xbc, 0xf2, 0xcc, 0xe5, 0xd6, 0xd0, 0xce, 0xc4, 0xb2, 0xe2, 0xca, 0xd4, 0xd7, 0xd6, 0xc4, 0xbb,
  0xc4, 0xe3, 0xba, 0xc3, 0xca, 0xc0, 0xbd, 0xe7, 0x20
];

function repeatedBytes(sample, count) {
  return Uint8Array.from(Array.from({ length: count }, () => sample).flat());
}

test("keeps valid Korean text when the bounded sample ends mid-character", () => {
  const expected = "안녕하세요 세상 한국어 자막 테스트입니다 ".repeat(120);

  assert.equal(decodeSubtitleBytes(repeatedBytes(EUC_KR_SAMPLE, 120)), expected);
});

test("keeps valid Chinese text when the bounded sample ends mid-character", () => {
  const expected = "简体中文测试字幕你好世界 ".repeat(220);

  assert.equal(decodeSubtitleBytes(repeatedBytes(GB18030_SAMPLE, 220)), expected);
});
